// Bundles the studio voice worker (src/worker.ts + the shared engine in src/voice/engine) into worker.mjs.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
const here = fileURLToPath(new URL(".", import.meta.url));
await build({
  entryPoints: [`${here}src/worker.ts`],
  outfile: `${here}worker.mjs`,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  external: ["onnxruntime-node"],
  banner: { js: "// Generated by desktop/voice/build.mjs from desktop/voice/src/worker.ts — do not edit." },
  logLevel: "warning",
});
console.log("voice/worker.mjs built");
