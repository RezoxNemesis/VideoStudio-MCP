/** Serialize the browser closure before esbuild injects Worker-scoped helpers. */
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import client from '../src/personal-client.js';
const directory=new URL('../.generated/',import.meta.url);
const destination=new URL('personal-client.js',directory);
const source='// Generated by scripts/bake-personal-client.mjs; do not edit.\nexport default '+JSON.stringify(client)+';\n';
await mkdir(directory,{recursive:true});
if(await readFile(destination,'utf8').catch(()=>null)!==source) await writeFile(destination,source);
